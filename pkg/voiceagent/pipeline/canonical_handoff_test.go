type fencedHandoffPlayer struct{}

func (*fencedHandoffPlayer) PlayStream(ctx context.Context, stream *audio.PCMStream) (*audio.Playback, error) {
	if _, err := stream.WaitReady(context.Background()); err != nil {
		return nil, err
	}
	attempt := audio.PlaybackAttemptFromContext(ctx)
	started := make(chan struct{})
	done := make(chan audio.PlaybackResult, 1)
	go func() {
		close(started)
		frames := 0
		firstWrite := false
		for samples := range stream.Frames() {
			frames += len(samples)
			if !firstWrite {
				firstWrite = attempt.Write(func() {})
			}
		}
		done <- attempt.Result(audio.PlaybackResult{AudioSeconds: float64(frames) / 24000})
		close(done)
	}()
	return audio.NewPlayback(started, done), nil
}
func (*fencedHandoffPlayer) Stop()            {}
func (*fencedHandoffPlayer) IsPlaying() bool  { return false }
func (*fencedHandoffPlayer) Close() error     { return nil }
func (*fencedHandoffPlayer) SinkKind() string { return audio.SinkLocalSpeaker }

type managedHandoffBrain struct {
	*handoffCompletionBrain
	runtime *delegation.Runtime
	closed  chan struct{}
}

func (b *managedHandoffBrain) DetachDelegation() *delegation.Runtime {
	r := b.runtime
	b.runtime = nil
	return r
}
func (b *managedHandoffBrain) AttachDelegation(r *delegation.Runtime) error {
	b.runtime = r
	return nil
}
func (b *managedHandoffBrain) Close() error {
	select {
	case <-b.closed:
	default:
		close(b.closed)
	}
	return nil
}

// handoffCompletionBrain is a provider-shaped fake: the worker is still
// admitted and completed through Agency and the completion request is still
// generated by runCanonicalCompletion.
type handoffCompletionBrain struct {
	*lifecycleWorker
	mu         sync.Mutex
	requests   []brain.CompletionRequest
	appended   []string
	history    []brain.Turn
	thinkCalls int
	omit       bool
	appendErr  error
}

func (b *handoffCompletionBrain) ThinkStream(ctx context.Context, input string, _ brain.StreamOptions) (*brain.Stream, error) {
	b.mu.Lock()
	b.thinkCalls++
	b.history = append(b.history, brain.Turn{Role: "user", Content: input})
	b.mu.Unlock()
	return scriptedStream(ctx, []string{"I can help with that."}, nil), nil
}

func (b *handoffCompletionBrain) Complete(ctx context.Context, req brain.CompletionRequest) (brain.CompletionEnvelope, error) {
	b.mu.Lock()
	b.requests = append(b.requests, req)
	omit := b.omit
	b.mu.Unlock()
	if err := ctx.Err(); err != nil {
		return brain.CompletionEnvelope{}, err
	}
	if omit {
		return brain.CompletionEnvelope{Answer: "Your other question is answered."}, nil
	}
	updates := make([]brain.CompletionUpdate, 0, len(req.Results))
	for _, r := range req.Results {
		updates = append(updates, brain.CompletionUpdate{ResultID: r.ResultID, Text: "Delivered " + r.Brief})
	}
	return brain.CompletionEnvelope{Updates: updates}, nil
}

func (b *handoffCompletionBrain) AppendAssistantResponse(text string) error {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.appendErr != nil {
		return b.appendErr
	}
	b.appended = append(b.appended, text)
	b.history = append(b.history, brain.Turn{Role: "assistant", Content: text})
	return nil
}

func (b *handoffCompletionBrain) History() []brain.Turn {
	b.mu.Lock()
	defer b.mu.Unlock()
	return append([]brain.Turn(nil), b.history...)
}

func (b *handoffCompletionBrain) requestCount() int {
	b.mu.Lock()
	defer b.mu.Unlock()
	return len(b.requests)
}

func (b *handoffCompletionBrain) lastRequest() brain.CompletionRequest {
	b.mu.Lock()
	defer b.mu.Unlock()
	if len(b.requests) == 0 {
		return brain.CompletionRequest{}
	}
	return b.requests[len(b.requests)-1]
}

func TestCanonicalHandoffSurvivesAdmissionAndBrainReplacement(t *testing.T) {
	jobs := job.NewTable(context.Background(), job.WithMaxConcurrent(1))
	t.Cleanup(jobs.Close)
	oldBrain := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "old foreground"}}
	nextBrain := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "next foreground"}}
	worker := &blockingWorker{started: make(chan struct{}), release: make(chan struct{}), reply: "weather is sunny. Source: weather.example. Limitation: forecast is approximate."}
	p := &Pipeline{Events: events.NewBus(), Brain: oldBrain}
	a := NewAgency(p, jobs, worker, &config.Config{VoiceWorkerProvider: "ollama", VoiceWorkerModel: "old", ActivePersona: "old-persona"}, nil)
	a.Wire()
	p.Agency = a
	if err := p.EnableConversationWork("handoff-session", nil, &config.Config{VoiceWorkerProvider: "ollama", VoiceWorkerModel: "old", ActivePersona: "old-persona"}); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = p.CloseWork() })

	deliveries := make(chan events.WorkDelivery, 16)
	events.Subscribe(p.Events, func(e events.WorkDelivery) { deliveries <- e })
	metrics := newTurnMetrics()
	a.HandleRoute(context.Background(), p.newTurnConductor(metrics), metrics, RouteDecision{Kind: RouteSpawn, Transcript: "check the weather", Source: "test"})
	select {
	case <-worker.started:
	case <-time.After(time.Second):
		t.Fatal("admitted worker did not start")
	}
	foreground := make(chan error, 1)
	go func() { foreground <- p.RunTurnTextMode(context.Background(), "what else should I check?") }()
	select {
	case err := <-foreground:
		if err != nil {
			t.Fatalf("unrelated foreground turn: %v", err)
		}
	case <-time.After(time.Second):
		t.Fatal("unrelated foreground turn blocked behind worker")
	}
	oldBrain.mu.Lock()
	foregroundCalls := oldBrain.thinkCalls
	oldBrain.mu.Unlock()
	if foregroundCalls != 1 {
		t.Fatalf("foreground calls while worker blocked=%d", foregroundCalls)
	}

	if err := p.ReplaceConversationBrain(nextBrain, &lifecycleWorker{reply: "next worker"}, &config.Config{VoiceWorkerProvider: "ollama", VoiceWorkerModel: "next", ActivePersona: "new-persona"}, nil); err != nil {
		t.Fatal(err)
	}
	close(worker.release)
	scope := p.WorkSnapshot().Scope
	pending := waitWorkPending(t, p.WorkCoordinator(), scope, 1)
	// Source/limitations may be empty for this worker, while frozen
	// origin/model must always remain attributable.
	if pending[0].Outcome.Model != "old" || pending[0].Outcome.Origin != "agency" || pending[0].Outcome.Config["persona"] != "old-persona" {
		t.Fatalf("frozen worker provenance=%+v", pending[0].Outcome)
	}
	t.Logf("trace: admission accepted -> worker blocked -> brain replaced -> terminal result %s", pending[0].Outcome.ResultID)

	tts := &fakeTTS{delay: time.Millisecond}
	p.Player = &fencedHandoffPlayer{}
	p.ReplaceTTS(tts, nil)
	if err := p.RunBackgroundTurn(context.Background()); err != nil {
		t.Fatal(err)
	}
	snapshot := p.WorkSnapshot()
	if len(snapshot.Pending) != 0 || len(snapshot.Communicated) != 1 {
		t.Fatalf("canonical delivery snapshot=%+v", snapshot)
	}
	communicated := snapshot.Communicated[0]
	if communicated.State != work.Communicated || communicated.LastAttempt == nil || !communicated.LastAttempt.Receipt.ResponseCommitted {
		t.Fatalf("delivery evidence=%+v", communicated)
	}
	receipt := communicated.LastAttempt.Receipt
	if receipt.Mode != "voice" || !receipt.Audible || !receipt.PlaybackComplete || receipt.Segments == 0 {
		t.Fatalf("sourced result lacked full voice delivery: %+v", receipt)
	}
	if nextBrain.requestCount() != 1 || len(tts.Texts()) == 0 || len(nextBrain.History()) != 1 {
		t.Fatalf("voice/history trace requests=%d tts=%v history=%v", nextBrain.requestCount(), tts.Texts(), nextBrain.History())
	}
	request := nextBrain.lastRequest()
	if len(request.Results) != 1 || request.Results[0].Origin != "old-persona" || !strings.Contains(request.Results[0].Brief, "weather.example") || !strings.Contains(request.Results[0].Brief, "approximate") {
		t.Fatalf("canonical request lost source/limitation=%+v", request.Results)
	}
	spoken := strings.Join(tts.Texts(), " ")
	if !strings.Contains(spoken, "weather.example") || !strings.Contains(spoken, "approximate") || !strings.Contains(nextBrain.History()[0].Content, "weather.example") {
		t.Fatalf("source/limitation lost in voice/history: spoken=%q history=%v", spoken, nextBrain.History())
	}
	// Persist the exact copied snapshot through the normal session store and
	// reload it; communicated records must survive without becoming pending.
	store := session.NewStore(t.TempDir())
	savedSession := session.New("ollama", "test")
	savedSession.ID = snapshot.Scope.SessionID
	if err := store.Save(savedSession, nil); err != nil {
		t.Fatal(err)
	}
	if err := store.BeginWork(savedSession, snapshot, nil); err != nil {
		t.Fatal(err)
	}
	reloaded, err := store.Load(savedSession.ID)
	if err != nil {
		t.Fatal(err)
	}
	if reloaded.Work == nil || len(reloaded.Work.Pending) != 0 || len(reloaded.Work.Communicated) != 1 {
		t.Fatalf("reloaded handoff=%+v", reloaded.Work)
	}
	destination := scope
	destination.RuntimeEpoch = "reloaded-runtime"
	restored := work.NewCoordinator(scope)
	if err := restored.Restore(*reloaded.Work, destination); err != nil {
		t.Fatal(err)
	}
	if got := restored.Snapshot(destination); len(got.Pending) != 0 || len(got.Communicated) != 1 || got.Communicated[0].LastAttempt.Receipt != receipt {
		t.Fatalf("restore lost the actual delivery receipt: %+v", got)
	}
	if nextBrain.requestCount() != 1 || oldBrain.requestCount() != 0 {
		t.Fatalf("completion provider calls old=%d next=%d", oldBrain.requestCount(), nextBrain.requestCount())
	}
	seenStages := map[string]bool{}
	deadline := time.After(time.Second)
collecting:
	for !seenStages["announcement.communicated"] {
		select {
		case d := <-deliveries:
			seenStages[d.Stage] = true
		case <-deadline:
			break collecting
		}
	}
	if !seenStages["result.projected"] || !seenStages["announcement.scheduled"] || !seenStages["announcement.addressed"] || !seenStages["announcement.communicated"] {
		t.Fatalf("delivery stages=%v", seenStages)
	}
	t.Logf("trace: result.projected -> announcement.scheduled -> announcement.addressed -> announcement.communicated; persisted communicated=%d", len(snapshot.Communicated))
}

func TestCanonicalHandoffFailuresRetainPendingWithoutRetryModelCall(t *testing.T) {
	t.Run("muted", func(t *testing.T) {
		p, c, scope := newCompletionLeasePipeline(t, false)
		provider := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "foreground"}}
		p.Brain = provider
		p.SetOutputMuted(true)
		if err := p.RunBackgroundTurn(context.Background()); err != nil {
			t.Fatal(err)
		}
		if len(c.Pending(scope)) != 1 || provider.requestCount() != 0 {
			t.Fatalf("muted pending=%+v completionCalls=%d", c.Pending(scope), provider.requestCount())
		}
	})

	t.Run("omitted-id", func(t *testing.T) {
		p, c, scope := newCompletionLeasePipeline(t, false)
		provider := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "foreground"}, omit: true}
		p.Brain = provider
		if err := p.RunBackgroundTurn(context.Background()); err != nil {
			t.Fatal(err)
		}
		pending := c.Pending(scope)
		if len(pending) != 1 || pending[0].State == work.Communicated || provider.requestCount() != 1 {
			t.Fatalf("omitted result pending=%+v completionCalls=%d", pending, provider.requestCount())
		}
		if err := p.RunBackgroundTurn(context.Background()); err != nil && !errors.Is(err, context.Canceled) {
			t.Fatal(err)
		}
		if provider.requestCount() != 1 {
			t.Fatalf("unbounded retry calls=%d", provider.requestCount())
		}
		if got := c.Pending(scope); len(got) != 0 || len(c.Snapshot(scope).Communicated) != 1 {
			t.Fatalf("explicit fallback did not communicate: pending=%+v snapshot=%+v", got, c.Snapshot(scope))
		}
	})

	t.Run("appender-failure", func(t *testing.T) {
		p, c, scope := newCompletionLeasePipeline(t, false)
		provider := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "foreground"}, appendErr: errors.New("history unavailable")}
		p.Brain = provider
		if err := p.RunBackgroundTurn(context.Background()); err != nil {
			t.Fatal(err)
		}
		pending := c.Pending(scope)
		if len(pending) != 1 || pending[0].State != work.Held || pending[0].HoldReason != "history_unavailable" {
			t.Fatalf("appender failure pending=%+v", pending)
		}
	})

	t.Run("voice-missing-receipt-is-held", func(t *testing.T) {
		p, c, scope := newCompletionLeasePipeline(t, false)
		provider := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "foreground"}}
		player := newFakePlayer(time.Millisecond)
		player.audioSeconds = 1
		t.Cleanup(func() { _ = player.Close() })
		p.Brain, p.Player, p.TTS = provider, player, &fakeTTS{delay: time.Millisecond}
		if err := p.RunBackgroundTurn(context.Background()); err != nil {
			t.Fatal(err)
		}
		snapshot := p.WorkSnapshot()
		if len(snapshot.Pending) != 1 || snapshot.Pending[0].State != work.Held || snapshot.Pending[0].HoldReason != "playback_failed" {
			t.Fatalf("voice failed receipt snapshot=%+v", snapshot)
		}
		if snapshot.Pending[0].LastAttempt == nil || snapshot.Pending[0].LastAttempt.Reason != "playback_failed" {
			t.Fatalf("voice failure evidence=%+v", snapshot.Pending[0].LastAttempt)
		}
		if len(provider.History()) != 1 || len(c.Pending(scope)) != 1 {
			t.Fatalf("voice history=%+v pending=%+v", provider.History(), c.Pending(scope))
		}
	})

	t.Run("voice-fenced-receipt-communicates", func(t *testing.T) {
		p, c, scope := newCompletionLeasePipeline(t, false)
		provider := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "foreground"}}
		p.Brain, p.Player, p.TTS = provider, &fencedHandoffPlayer{}, &fakeTTS{delay: time.Millisecond}
		if err := p.RunBackgroundTurn(context.Background()); err != nil {
			t.Fatal(err)
		}
		snapshot := p.WorkSnapshot()
		if len(snapshot.Pending) != 0 || len(snapshot.Communicated) != 1 {
			t.Fatalf("fenced voice snapshot=%+v", snapshot)
		}
		evidence := snapshot.Communicated[0].LastAttempt
		if evidence == nil || evidence.Receipt.Mode != "voice" || !evidence.Receipt.PlaybackComplete || !evidence.Receipt.Audible || evidence.Receipt.Segments == 0 {
			t.Fatalf("fenced voice receipt=%+v", evidence)
		}
		if len(provider.History()) != 1 || len(c.Pending(scope)) != 0 {
			t.Fatalf("fenced voice history=%+v pending=%+v", provider.History(), c.Pending(scope))
		}
	})

	t.Run("tts-failure-requires-explicit-recovery", func(t *testing.T) {
		p, c, scope := newCompletionLeasePipeline(t, false)
		provider := &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "foreground"}}
		p.Brain, p.Player, p.TTS = provider, &fencedHandoffPlayer{}, &errTTS{err: errors.New("tts unavailable")}
		if err := p.RunBackgroundTurn(context.Background()); err != nil {
			t.Fatal(err)
		}
		got := c.Pending(scope)
		if len(got) != 1 || got[0].State != work.Held || got[0].HoldReason != "playback_failed" || provider.requestCount() != 1 {
			t.Fatalf("tts failure pending=%+v calls=%d", got, provider.requestCount())
		}
		for range 3 {
			if err := p.RunBackgroundTurn(context.Background()); err != nil {
				t.Fatal(err)
			}
		}
		if p.BackgroundPending() || provider.requestCount() != 1 {
			t.Fatal("held TTS failure retried on a passive scheduler tick")
		}
		p.ReplaceTTS(&fakeTTS{}, nil)
		if got := c.Pending(scope); len(got) != 1 || got[0].State != work.Ready {
			t.Fatalf("explicit recovery did not resume=%+v", got)
		}
		if err := p.RunBackgroundTurn(context.Background()); err != nil {
			t.Fatal(err)
		}
		if len(c.Pending(scope)) != 0 || len(c.Snapshot(scope).Communicated) != 1 {
			t.Fatal("recovered output did not deliver held obligation")
		}
	})
}

func TestCanonicalManagedRuntimeHandoffCarriesTerminalSource(t *testing.T) {
	client := &managedHarnessClient{started: make(chan delegation.Request, 1), result: make(chan delegation.Snapshot, 1), canceled: make(chan struct{})}
	runtime, err := delegation.New(context.Background(), client, time.Minute, nil)
	if err != nil {
		t.Fatal(err)
	}
	brain := &managedHandoffBrain{handoffCompletionBrain: &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "foreground"}}, runtime: runtime, closed: make(chan struct{})}
	p := &Pipeline{Events: events.NewBus(), Brain: brain}
	jobs := job.NewTable(context.Background())
	t.Cleanup(func() { jobs.Close(); _ = p.CloseWork() })
	a := NewAgency(p, jobs, &lifecycleWorker{reply: "agency"}, &config.Config{VoiceWorkerProvider: "ollama"}, nil)
	a.Wire()
	p.Agency = a
	if err := p.EnableConversationWork("managed-handoff", nil, &config.Config{VoiceWorkerProvider: "ollama", ActivePersona: "original-persona"}); err != nil {
		t.Fatal(err)
	}
	ticket, err := runtime.Start("weather source")
	if err != nil {
		t.Fatal(err)
	}
	req := <-client.started
	if req.Key != ticket {
		t.Fatalf("managed request key=%q ticket=%q", req.Key, ticket)
	}
	client2 := &managedHarnessClient{started: make(chan delegation.Request, 1), result: make(chan delegation.Snapshot, 1), canceled: make(chan struct{})}
	runtime2, err := delegation.New(context.Background(), client2, time.Minute, nil)
	if err != nil {
		t.Fatal(err)
	}
	next := &managedHandoffBrain{handoffCompletionBrain: &handoffCompletionBrain{lifecycleWorker: &lifecycleWorker{reply: "next foreground"}}, runtime: runtime2, closed: make(chan struct{})}
	if err := p.ReplaceConversationBrain(next, &lifecycleWorker{reply: "next worker"}, &config.Config{VoiceWorkerProvider: "ollama", ActivePersona: "new-persona"}, nil); err != nil {
		t.Fatal(err)
	}
	client.result <- delegation.Snapshot{ID: ticket, State: "completed", Text: "Sunny. Source: weather.example."}
	scope := p.WorkSnapshot().Scope
	waitWorkPending(t, p.WorkCoordinator(), scope, 1)
	if err := p.RunBackgroundTurn(context.Background()); err != nil {
		t.Fatal(err)
	}
	snapshot := p.WorkSnapshot()
	if len(snapshot.Pending) != 0 || len(snapshot.Communicated) != 1 {
		t.Fatalf("managed handoff snapshot=%+v", snapshot)
	}
	if snapshot.Communicated[0].Outcome.SourceRef != ticket {
		t.Fatalf("managed terminal source=%q, want original backend reference %q", snapshot.Communicated[0].Outcome.SourceRef, ticket)
	}
	if snapshot.Communicated[0].Outcome.Origin != "managed" {
		t.Fatalf("managed origin changed after replacement=%q", snapshot.Communicated[0].Outcome.Origin)
	}
	r := snapshot.Communicated[0]
	if r.Outcome.Config["persona"] != "original-persona" || r.LastAttempt.Receipt.Mode != "text" || !r.LastAttempt.Receipt.ResponseCommitted || next.requestCount() != 1 || brain.requestCount() != 0 {
		t.Fatalf("managed current binding receipt/provenance: %+v", r)
	}
}
