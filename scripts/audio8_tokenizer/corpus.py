def all_cases() -> list[str]:
    seen: dict[str, None] = {}
    for group in (
        PROMPT_FRAGMENTS,
        ENGLISH,
        UNICODE,
        EMOJI,
        WHITESPACE,
        ADDED_TOKENS,
        SYMBOLS,
        MIXED,
    ):
        for text in group:
            seen.setdefault(text, None)
    return list(seen)
