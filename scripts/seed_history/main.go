// seed_history regenerates pkg/voiceagent/prompts/seed_history.go: the sha256
// of every version of every embedded default prompt that any commit in this
// repository has carried, keyed by the <kind>/<name>.yaml path Seed writes it
// to. Run from the repository root:
//
//	go run ./scripts/seed_history > pkg/voiceagent/prompts/seed_history.go
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"slices"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

var defaultsDirs = []string{"internal/prompts/defaults", "pkg/voiceagent/prompts/defaults"}

func main() {
	if err := run(context.Background()); err != nil {
		fmt.Fprintln(os.Stderr, "seed_history:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context) error {
	commits, err := git(ctx, append([]string{"log", "--all", "--full-history", "--format=%H", "--"}, defaultsDirs...)...)
	if err != nil {
		return err
	}

	blobs := map[string]bool{}
	for _, commit := range strings.Fields(string(commits)) {
		tree, err := git(ctx, append([]string{"ls-tree", "-r", commit, "--"}, defaultsDirs...)...)
		if err != nil {
			return err
		}
		for _, line := range strings.Split(strings.TrimSpace(string(tree)), "\n") {
			meta, path, ok := strings.Cut(line, "\t")
			fields := strings.Fields(meta)
			if !ok || len(fields) != 3 || fields[1] != "blob" || !strings.HasSuffix(path, ".yaml") {
				continue
			}
			blobs[fields[2]] = true
		}
	}

	table := map[string][]string{}
	for blob := range blobs {
		data, err := git(ctx, "cat-file", "blob", blob)
		if err != nil {
			return err
		}
		var doc struct {
			Prompt struct {
				Name string `yaml:"name"`
				Kind string `yaml:"kind"`
			} `yaml:"prompt"`
		}
		if err := yaml.Unmarshal(data, &doc); err != nil {
			return fmt.Errorf("blob %s: %w", blob, err)
		}
		if doc.Prompt.Kind == "" || doc.Prompt.Name == "" {
			return fmt.Errorf("blob %s: missing prompt kind or name", blob)
		}
		rel := doc.Prompt.Kind + "/" + doc.Prompt.Name + ".yaml"
		sum := sha256.Sum256(data)
		table[rel] = append(table[rel], hex.EncodeToString(sum[:]))
	}

	paths := make([]string, 0, len(table))
	for rel := range table {
		paths = append(paths, rel)
	}
	sort.Strings(paths)

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./scripts/seed_history; DO NOT EDIT.\n\n")
	b.WriteString("package prompts\n\n")
	b.WriteString("// shippedHistory holds the sha256 of every version of each default document\n")
	b.WriteString("// released before Seed kept a manifest, keyed by the path Seed writes it to.\n")
	b.WriteString("// It recognises untouched copies on installs that predate the manifest and\n")
	b.WriteString("// never needs extending: the manifest records every version written since.\n")
	b.WriteString("var shippedHistory = map[string][]string{\n")
	for _, rel := range paths {
		sums := table[rel]
		slices.Sort(sums)
		fmt.Fprintf(&b, "\t%q: {\n", rel)
		for _, sum := range slices.Compact(sums) {
			fmt.Fprintf(&b, "\t\t%q,\n", sum)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("formatting output: %w", err)
	}
	_, err = os.Stdout.Write(src)
	return err
}

func git(ctx context.Context, args ...string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, "git", args...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return out, nil
}
